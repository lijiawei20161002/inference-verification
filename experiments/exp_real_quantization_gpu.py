TEMPLATES = (
    "Explain how to compute {a} plus {b} and check the result.",
    "Write a Python function that sorts [{a}, {b}, {c}] and removes duplicates.",
    "Describe a fictional island with {a} residents and {b} trees.",
    "A database has {a} records across {d} servers. Explain a balanced partition.",
    "A train travels {d} kilometers in {e} minutes. Explain its average speed.",
    "Write a short story about a library with {a} books and room number {b}.",
    "Explain how a cache could store keys {a}, {b}, and {c} with eviction.",
    "Compare two gardens with areas {a} and {b} square meters. Suggest a layout.",
)


def make_corpus(tokenizer, calibration, evaluation, seed):
    """Distinct, untruncated tokenized prompts, independent partition RNGs."""
    rows = []
    for split, n, offset in (("calibration", calibration, 1), ("evaluation", evaluation, 2)):
        rng = random.Random(seed * 1009 + offset)
        for _ in range(n):
            a, b, c = (rng.randrange(100, 99999) for _ in range(3))
            text = rng.choice(TEMPLATES).format(a=a, b=b, c=c,
                                               d=rng.randrange(2, 80), e=rng.randrange(3, 100))
            ids = tokenizer.encode(text, add_special_tokens=False)
            if not ids or len(ids) > 128:
                raise ValueError("Prompt outside the predeclared length limit")
            rows.append(dict(prompt_id=len(rows), partition=split, text=text,
                             prompt_tokens=ids, sampling_seed=rng.randrange(1, 2**31)))
    if len({tuple(r["prompt_tokens"]) for r in rows}) != len(rows):
        raise ValueError("Prompt collision; choose another corpus seed")
    if len({r["sampling_seed"] for r in rows}) != len(rows):
        raise ValueError("Sampling seed collision; choose another corpus seed")
    return rows


def load_model(snapshot, arm):
    import bitsandbytes as bnb
    import torch
    from transformers import AutoModelForCausalLM, BitsAndBytesConfig

    kw = dict(dtype=torch.bfloat16, attn_implementation="eager",
              device_map={"": 0}, local_files_only=True)
    if arm == "nf4":
        kw["quantization_config"] = BitsAndBytesConfig(
            load_in_4bit=True, bnb_4bit_quant_type="nf4",
            bnb_4bit_compute_dtype=torch.bfloat16, bnb_4bit_use_double_quant=True)
    elif arm == "int8":
        kw["quantization_config"] = BitsAndBytesConfig(load_in_8bit=True,
                                                     llm_int8_threshold=6.0)
    elif arm != "bf16":
        raise ValueError(f"Unknown arm: {arm}")
    model = AutoModelForCausalLM.from_pretrained(snapshot, **kw).eval()
    qcls = bnb.nn.Linear4bit if arm == "nf4" else bnb.nn.Linear8bitLt
    quantized = [(name, module) for name, module in model.named_modules()
                 if isinstance(module, qcls)] if arm != "bf16" else []
    if arm != "bf16":
        if not quantized:
            raise RuntimeError("Requested quantization did not replace any linear layers")
        expected_dtype = torch.uint8 if arm == "nf4" else torch.int8
        if any(m.weight.dtype != expected_dtype for _, m in quantized):
            raise RuntimeError("Quantized weights are not packed on the GPU")
        if arm == "nf4" and any(m.weight.quant_state.quant_type != "nf4" for _, m in quantized):
            raise RuntimeError("Loaded 4-bit weights are not NF4")
    if any(p.device.type != "cuda" for p in model.parameters()):
        raise RuntimeError("CPU/offloaded weights would change the experiment")
    info = dict(arm=arm, footprint_bytes=model.get_memory_footprint(),
                quantized_linear_modules=[name for name, _ in quantized],
                quantized_weight_dtypes=sorted({str(m.weight.dtype) for _, m in quantized}),
                quantization_config=kw["quantization_config"].to_dict()
                if "quantization_config" in kw else None)
    if arm == "int8":
        info["kernel_input_cast"] = "bitsandbytes MatMul8bitLt casts BF16 inputs to FP16"
    return model, info


def generate(model, row, tokens, proj):
    import torch
    spec = SamplingSpec(seed=row["sampling_seed"])
    x = torch.tensor([row["prompt_tokens"]], device="cuda")
    claimed, fps, logits = [], [], []
    with torch.inference_mode():
        out = model(x, use_cache=True, output_hidden_states=True)
        for pos in range(tokens):
            values = out.logits[0, -1].float().cpu().numpy()
            hidden = out.hidden_states[-1][0, -1].float().cpu().numpy()
            g = gumbel_noise(len(values), position_seed(spec.seed, row["prompt_id"], pos))
            token = gumbel_max_sample(values, spec.temperature, g, spec.top_k, spec.top_p)
            claimed.append(token)
            logits.append(values)
            fps.append(proj @ hidden)
            if pos + 1 < tokens:
                out = model(torch.tensor([[token]], device="cuda"),
                            past_key_values=out.past_key_values, use_cache=True,
                            output_hidden_states=True)
    return claimed, np.asarray(fps), np.asarray(logits)


def reference(model, row, claimed):
    import torch
    # Include the final claimed token to match ShapeBackend's chunked_b1 layout.
    x = torch.tensor([row["prompt_tokens"] + claimed], device="cuda")
    start = len(row["prompt_tokens"]) - 1
    idx = slice(start, start + len(claimed))
    with torch.inference_mode():
        out = model(x, use_cache=True, output_hidden_states=True)
    return (out.logits[0, idx].float().cpu().numpy(),
            out.hidden_states[-1][0, idx].float().cpu().numpy())


def score(row, claimed, fps, ref_logits, ref_hidden, proj):
    spec = SamplingSpec(seed=row["sampling_seed"])
    # harness.verify promotes reference logits to float64 before evidence().
    ref_logits = np.asarray(ref_logits, dtype=np.float64)
    scores = {name: [] for name in DETECTORS}
    for pos, token in enumerate(claimed):
        g = gumbel_noise(ref_logits.shape[1], position_seed(spec.seed, row["prompt_id"], pos))
        ref_fp = proj @ ref_hidden[pos]
        for name in DETECTORS:
            scores[name].append(verifiers.get(name).score_token(
                ref_logits[pos], g, token, spec, fps[pos], ref_fp))
    return {k: np.asarray(v) for k, v in scores.items()}


def run(args, manifest):
    import torch
    from huggingface_hub import snapshot_download
    from transformers import AutoTokenizer

    plan = dict(schema="ivgym-real-quantization-plan-v1", model=args.model,
                revision=args.revision, calibration=args.calibration,
                evaluation=args.evaluation, tokens=args.tokens, corpus_seed=args.seed,
                alpha=0.05, bootstrap=args.bootstrap, arms=list(ARMS),
                sampling=asdict(SamplingSpec()), sampling_seed_policy="fresh per corpus row",
                sampling_arithmetic="float32 provider logits; float64 verifier logits, matching harness",
                provider_shape="sequential_eager_batch1", reference_shape="chunked_eager_batch1",
                injected_noise=False, eos_policy="continue to fixed token count",
                prompt_policy="raw text; no chat template; no truncation",
                projection=dict(seed=123, dimension=32),
                threshold_statistic="raw mean of all token scores in one sequence",
                effect_statistic="evaluation per-token mean shift / BF16 population SD",
                effect_cap="BF16 evaluation 99.9 percentile; recomputed in each bootstrap draw",
                bootstrap_unit="paired prompt and seed; generated tokens may differ",
                interval="exploratory 90 percent; not simultaneous")
    write_json(args.output / "plan.json", plan)
    snapshot = snapshot_download(args.model, revision=args.revision, local_files_only=True)
    # Inventory the actual model assets, including the original BF16 weight shards.
    manifest["model_assets_sha256"] = {
        p.name: digest(p) for p in sorted(Path(snapshot).iterdir()) if p.is_file()}
    tokenizer = AutoTokenizer.from_pretrained(snapshot, local_files_only=True)
    corpus = make_corpus(tokenizer, args.calibration, args.evaluation, args.seed)
    write_json(args.output / "corpus.json", corpus)
    reference_model, reference_info = load_model(snapshot, "bf16")
    manifest["reference_model"] = reference_info
    manifest["vocab"] = int(reference_model.config.vocab_size)
    proj = projection(123, 32, int(reference_model.config.hidden_size))
    arrays = {}
    manifest["arms"] = {}
    for arm in ARMS:
        arm_start = time.monotonic()
        model, info = load_model(snapshot, arm)
        assert model is not reference_model
        torch.cuda.reset_peak_memory_stats()
        times = {"generation": 0.0, "reference": 0.0, "reference_rerun": 0.0,
                 "score_and_diagnostics": 0.0}
        lists = {d: [] for d in (*DETECTORS, *DIAGNOSTICS)}
        rerun_lists = {d: [] for d in DETECTORS}
        all_logits_exact = all_hidden_exact = True
        with gzip.open(args.output / f"capture_{arm}.jsonl.gz", "wt") as capture:
            for i, row in enumerate(corpus):
                torch.cuda.synchronize()
                start = time.monotonic()
                claimed, fps, served = generate(model, row, args.tokens, proj)
                torch.cuda.synchronize()
                times["generation"] += time.monotonic() - start
                capture.write(json.dumps(dict(prompt_id=row["prompt_id"],
                                              claimed_tokens=claimed, fingerprints=fps.tolist()),
                                         allow_nan=False) + "\n")
                capture.flush()
                refs = []
                for timing in ("reference", "reference_rerun"):
                    start = time.monotonic()
                    refs.append(reference(reference_model, row, claimed))
                    torch.cuda.synchronize()
                    times[timing] += time.monotonic() - start
                lg, hidden = refs[0]
                all_logits_exact &= np.array_equal(lg, refs[1][0])
                all_hidden_exact &= np.array_equal(hidden, refs[1][1])
                start = time.monotonic()
                for result, target in ((score(row, claimed, fps, lg, hidden, proj), lists),
                                       (score(row, claimed, fps, *refs[1], proj), rerun_lists)):
                    for d, values in result.items():
                        target[d].append(values)
                delta = served.astype(np.float64) - lg
                lists["logit_mae"].append(np.abs(delta).mean(axis=1))
                lists["logit_rms"].append(np.sqrt(np.mean(delta ** 2, axis=1)))
                lists["logit_max_abs"].append(np.abs(delta).max(axis=1))
                times["score_and_diagnostics"] += time.monotonic() - start
                if (i + 1) % 4 == 0 or i + 1 == len(corpus):
                    print(json.dumps(dict(arm=arm, sequences=i + 1, total=len(corpus),
                                          elapsed_seconds=round(time.monotonic() - arm_start, 2))),
                          flush=True)
                del served, refs, lg, hidden, delta
        for name, values in lists.items():
            arrays[f"{arm}/{name}"] = np.asarray(values)
        for name, values in rerun_lists.items():
            arrays[f"rerun/{arm}/{name}"] = np.asarray(values)
        info.update(seconds=times, elapsed_seconds=time.monotonic() - arm_start,
                    peak_cuda_allocated_bytes=torch.cuda.max_memory_allocated(),
                    reference_logits_rerun_exact=bool(all_logits_exact),
                    reference_hidden_rerun_exact=bool(all_hidden_exact))
        manifest["arms"][arm] = info
        write_json(args.output / "manifest.json", manifest)
        np.savez_compressed(args.output / "scores.npz", **arrays)
        del model
        gc.collect()
        torch.cuda.empty_cache()
    result = summarize(plan, arrays)
    write_json(args.output / "summary.json", result)
    names = ["plan.json", "corpus.json", "scores.npz", "summary.json"]
    names += [f"capture_{arm}.jsonl.gz" for arm in ARMS]
    manifest["artifacts_sha256"] = {name: digest(args.output / name) for name in names}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--model", default=MODEL)
    parser.add_argument("--revision", default=REVISION)
    parser.add_argument("--calibration", type=int, default=32)
    parser.add_argument("--evaluation", type=int, default=64)
    parser.add_argument("--tokens", type=int, default=128)
    parser.add_argument("--seed", type=int, default=20261018)
    parser.add_argument("--bootstrap", type=int, default=1000)
    args = parser.parse_args()
    if min(args.calibration, args.evaluation, args.tokens, args.bootstrap) < 1:
        parser.error("Counts must be positive")
    if not re.fullmatch(r"[0-9a-f]{40}", args.revision):
        parser.error("Revision must be an immutable model commit SHA")
    args.output.mkdir(parents=True, exist_ok=False)
    # bnb logs this expected cast for every linear layer of every decode step.
    # Keep its first occurrence and record the arithmetic explicitly in metadata.
    class OnceCastWarning(logging.Filter):
        seen = False

        def filter(self, record):
            if record.getMessage().startswith("MatMul8bitLt: inputs will be cast"):
                if self.seen:
                    return False
                self.seen = True
            return True

    logging.getLogger("bitsandbytes.autograd._functions").addFilter(OnceCastWarning())
    started = time.monotonic()
    manifest = dict(schema="ivgym-real-quantization-run-v1", status="running",
                    started_utc=datetime.now(timezone.utc).isoformat())
    try:
        with ExitStack() as locks:
            lock_root = Path(tempfile.gettempdir())
            locks.enter_context(host_lock(lock_root / f"ivgym-research-{os.getuid()}.lock",
                                          shared=True))
            uuid = gpu_uuid(os.environ.get("CUDA_VISIBLE_DEVICES", "0"))
            locks.enter_context(host_lock(lock_root / f"ivgym-research-{os.getuid()}-{uuid}.lock"))
            manifest["provenance"] = provenance()
            p = manifest["provenance"]
            p["python"] = platform.python_version()
            p["software"]["bitsandbytes"] = importlib.metadata.version("bitsandbytes")
            for name in ("exp_real_quantization_gpu.py", "analyze_real_quantization.py"):
                p["source_sha256"][f"experiments/{name}"] = digest(ROOT / "experiments" / name)
            p["source_status"] = subprocess.check_output(
                ["git", "status", "--porcelain"], cwd=ROOT, text=True).strip()
            write_json(args.output / "manifest.json", manifest)
            run(args, manifest)
            manifest["status"] = "complete"
    except BaseException as exc:
        manifest.update(status="failed", error=f"{type(exc).__name__}: {exc}")
        raise
    finally:
        manifest.update(elapsed_seconds=time.monotonic() - started,
                        finished_utc=datetime.now(timezone.utc).isoformat())
        write_json(args.output / "manifest.json", manifest)


if __name__ == "__main__":
    main()
