"""Actual NF4 / INT8 providers against an independent BF16 reference on one GPU.

Fresh raw prompts and sampling seeds are matched across arms. Each continuation
is generated by its provider's weights with sequential eager decoding. The
reference scores that arm's claimed prefixes with one eager batch-1 prefill.
There is no injected logit or activation noise. Fixed-length continuations keep
EOS tokens, as in the existing token harness; this is not a live serving test.
"""
