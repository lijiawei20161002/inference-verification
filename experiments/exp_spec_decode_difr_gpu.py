"""Does an honest speculative-decoding server look honest to a DiFR verifier?

The claim under test
-------------------
A speculative-decoding server proposes tokens with a small draft model and uses
the reference model `M` only to accept, reject or resample them. The output law is
*exactly* `M`'s (proved in `ivgym/spec_server.py:emit_token`, measured on CPU in
`tests/test_spec_server.py`), but the internal sequence of logits and random draws
is not the one an ordinary decode produces. So a verifier that reruns `M` under the
same public seed and compares per-token sampling margins is comparing against a
map the honest server never used -- and an honest speculative provider may be
indistinguishable from a cheating non-speculative one.

This experiment measures that on real models, under the repo's one standardized
protocol (`harness.EvalConfig`: standardized pAUC @ FPR <= 0.5%, out-of-sample
threshold, enforced batch/pool ceiling).

The arms
--------
Target `M` = Qwen3-1.7B, draft = Qwen3-0.6B, one H100. Every arm is generated by
the same backend instance with the same `SamplingSpec`, so nothing but the
provider's procedure differs.

  honest              ordinary sequential decode, seed-synced Gumbel-Max. The null.
  honest_null         the SAME honest config on a DISJOINT prompt range. Not a
                      deviation -- the measured floor of this protocol, so every
                      other row is read against a real number rather than against
                      a theoretical 0.5.
  honest_spec         exact speculative decoding. HONEST: output law == M's.
  honest_spec_seeded  the same, with acceptance uniforms drawn from the public
                      per-position seed (replayable; see exp_spec_aware_verifier).
  spec_lenient        a CHEATING speculative server: threshold acceptance instead
                      of `min(1, p/q)`, correction drawn from `p` instead of the
                      residual. Accepts more drafts => fewer target passes => real
                      money, and pulls the served distribution toward the 0.6B.
  spec_topk           the other common shortcut: accept if the draft is in `p`'s
                      top-8.
  seed_43             the existing wrong-seed attack. The README calls it the clean
                      case for recomputation (token_difr 1.000, everything else at
                      chance) because reseeding redraws from the same distribution.
                      It is the correct comparison for honest speculation, which
                      also redraws from the same distribution.
  quant_2bit          a forward-pass cheat, for contrast: a deviation that changes
                      the distribution rather than the draw.

What is printed
---------------
  1. the speculative server's realized statistics -- it really did speculate;
  2. detection AUC, mean +- sd over protocol seeds, with the batch/pool ratio;
  3. per-token d' and the batch each cell would need for AUC 0.90;
  4. the deployment number: flag rate at a threshold calibrated to 0.5% FPR on
     honest traffic. For `honest_null` this must come back at ~0.5% (it is the
     protocol's own calibration check); for `honest_spec` it is a false-positive
     rate;
  5. the honesty certificate: seed-free statistics of the emitted tokens under the
     recomputed reference;
  6. the alibi cost: best AUC per attack with and without `token_difr`, i.e. what a
     verifier gives up once it must tolerate speculative decoding.

Run:  .venv/bin/python -m experiments.exp_spec_decode_difr_gpu
Env:  IVGYM_MODEL, IVGYM_DRAFT, IVGYM_PROMPTS, IVGYM_TOKENS, IVGYM_GAMMA,
      IVGYM_SEEDS, IVGYM_OUT
"""
from __future__ import annotations

import json
import os
import sys
import time
from dataclasses import replace
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ivgym import attacks, harness, signal, verifiers
from ivgym.backends.hf_gpu_spec import SpecDecodeHFBackend
from ivgym.core import SamplingSpec

MODEL = os.environ.get("IVGYM_MODEL", "Qwen/Qwen3-1.7B")
DRAFT = os.environ.get("IVGYM_DRAFT", "Qwen/Qwen3-0.6B")
N_PROMPTS = int(os.environ.get("IVGYM_PROMPTS", 48))
N_TOKENS = int(os.environ.get("IVGYM_TOKENS", 96))
GAMMA = int(os.environ.get("IVGYM_GAMMA", 4))
N_SEEDS = int(os.environ.get("IVGYM_SEEDS", 5))
OUT = Path(os.environ.get(
    "IVGYM_OUT", Path(__file__).resolve().parents[1] / "docs/results/spec_decode_difr.json"))

VERIFIERS = ["token_difr", "cross_entropy", "token_toploc", "activation_difr"]
# The verifier subset that survives a provider being allowed to speculate: every
# score that does NOT depend on reproducing the provider's random draws.
SEED_FREE = ["cross_entropy", "token_toploc", "activation_difr"]

# (arm name, prompt offset). `honest_null` is the same honest config on a disjoint
# prompt range -- the protocol's measured floor.
ARMS = [
    ("honest_null", N_PROMPTS),
    ("honest_spec", 0),
    ("honest_spec_seeded", 0),
    ("spec_lenient", 0),
    ("spec_topk", 0),
    ("seed_43", 0),
    ("quant_2bit", 0),
]
HONEST_ARMS = {"honest_null", "honest_spec", "honest_spec_seeded"}


def _dataset(backend, name, offset, spec):
    """Generate `N_PROMPTS` sequences for one arm, from `offset` in the prompt bank."""
    atk = attacks.get(name if name != "honest_null" else "honest")
    return [backend.generate(offset + p, N_TOKENS, spec, atk, True) for p in range(N_PROMPTS)]


def _fmt(mu, sd):
    return f"{mu:.3f}+-{sd:.3f}"


def main():
    t0 = time.time()
    print(f"loading target={MODEL} draft={DRAFT} gamma={GAMMA} ...", flush=True)
    backend = SpecDecodeHFBackend(model_name=MODEL, draft_model_name=DRAFT, gamma=GAMMA)
    print(f"loaded in {time.time()-t0:.1f}s | target {backend.n_params/1e9:.2f}B, "
          f"draft {backend.draft_n_params/1e9:.2f}B, vocab {backend.vocab} | "
          f"{N_PROMPTS} prompts x {N_TOKENS} tokens per arm", flush=True)

    spec = SamplingSpec()
    defs = [verifiers.get(d) for d in VERIFIERS]
    cfg = harness.EvalConfig()

    pool = N_PROMPTS * N_TOKENS
    eval_split = int(pool * (1.0 - cfg.calib_frac))
    batch = max(1, int(eval_split * cfg.max_pool_ratio))

    # --- the honest null (prompts [0, N)) -----------------------------------
    print("\ngenerating honest (non-speculative) null ...", flush=True)
    t = time.time()
    honest_seqs = _dataset(backend, "honest", 0, spec)
    honest = harness.verify(backend, honest_seqs, spec, defs)
    print(f"  {len(honest.scores[VERIFIERS[0]])} tokens in {time.time()-t:.1f}s", flush=True)

    scored, spec_runs = {}, {}
    for name, offset in ARMS:
        t = time.time()
        backend.spec_stats.clear()
        seqs = _dataset(backend, name, offset, spec)
        scored[name] = harness.verify(backend, seqs, spec, defs)
        if backend.spec_stats:
            spec_runs[name] = backend.spec_summary()
        print(f"  {name:19s} {len(scored[name].scores[VERIFIERS[0]]):5d} tokens "
              f"in {time.time()-t:5.1f}s", flush=True)

    # ---------------------------------------------------------------- 1. the server
    print("\n" + "=" * 78)
    print("1. The speculative server really speculated")
    print("=" * 78)
    print(f"{'arm':>19} | {'accept':>7} {'acc/round':>10} {'tok/round':>10} "
          f"{'bonus':>7} {'rounds':>7}")
    print("-" * 78)
    for name, s in spec_runs.items():
        print(f"{name:>19} | {s['accept_rate']:>7.3f} {s['mean_accepted']:>10.2f} "
              f"{s['tokens_per_round']:>10.2f} {s['bonus_frac']:>7.3f} {s['rounds']:>7d}")
    if "honest_spec" in spec_runs:
        s = spec_runs["honest_spec"]
        print(f"\n  Honest exact speculation emits {s['tokens_per_round']:.2f} tokens per "
              f"target verify pass at gamma={s['gamma']}, i.e. a "
              f"{s['tokens_per_round']:.2f}x reduction in target forward passes. This is "
              f"a server with a real reason to exist, not a strawman.")
    if "spec_lenient" in spec_runs:
        print(f"  The lenient CHEAT accepts {spec_runs['spec_lenient']['accept_rate']:.3f} "
              f"of drafts vs {spec_runs['honest_spec']['accept_rate']:.3f} honest -- it is "
              f"cheaper, which is why a provider would run it.")

    # ------------------------------------------------------- 2. detection AUC
    print("\n" + "=" * 78)
    print(f"2. Detection AUC @ FPR<=0.5%   (batch={batch} tokens, honest eval "
          f"pool={eval_split}, batch/pool={batch/eval_split:.1%})")
    print(f"   mean +- sd over {N_SEEDS} protocol seeds")
    print("=" * 78)
    header = f"{'arm':>19} | " + " ".join(f"{d:>16}" for d in VERIFIERS)
    print(header)
    print("-" * len(header))
    auc, tpr = {}, {}
    for name, _ in ARMS:
        auc[name], tpr[name] = {}, {}
        rows = [harness.evaluate(honest, scored[name], defs, [batch],
                                 config=replace(cfg, seed=s)) for s in range(N_SEEDS)]
        for d in VERIFIERS:
            a = np.array([[r.auc for r in row if r.defense == d][0] for row in rows])
            t_ = np.array([[r.tpr for r in row if r.defense == d][0] for row in rows])
            auc[name][d] = (float(a.mean()), float(a.std()))
            tpr[name][d] = (float(t_.mean()), float(t_.std()))
        print(f"{name:>19} | " + " ".join(f"{_fmt(*auc[name][d]):>16}" for d in VERIFIERS))
    print("\n  `honest_null` is an honest provider measured against another honest\n"
          "  provider: it is what 'no deviation' reads as under this protocol.")

    # ---------------------------------------------------------------- 3. d'
    print("\n" + "=" * 78)
    print("3. Per-token effect size d'  /  batch it nominates for AUC 0.90")
    print("=" * 78)
    print(header)
    print("-" * len(header))
    dprime = {}
    for name, _ in ARMS:
        dprime[name] = {}
        cells = []
        for d in VERIFIERS:
            dp = signal.per_token_stats(honest.scores[d], scored[name].scores[d],
                                        cfg.winsor_pct)["d_prime"]
            need = signal.batch_for_pauc(dp, 0.90, cfg.max_fpr)
            dprime[name][d] = float(dp)
            cells.append(f"{dp:+.3f} / {'--' if need < 0 or need > 99999 else need}")
        print(f"{name:>19} | " + " ".join(f"{c:>16}" for c in cells))

    # ------------------------------------------- 4. the deployment number (FPR)
    print("\n" + "=" * 78)
    print("4. Flag rate at a threshold calibrated to 0.5% FPR on honest traffic")
    print("   For an HONEST arm this is a FALSE-POSITIVE rate.")
    print("=" * 78)
    print(header)
    print("-" * len(header))
    for name, _ in ARMS:
        tag = "  <- honest" if name in HONEST_ARMS else ""
        print(f"{name:>19} | " + " ".join(f"{tpr[name][d][0]:>15.1%} " for d in VERIFIERS)
              + tag)
    # `honest_null` differs from the null only in which prompts it ran on, so its
    # flag rate is the protocol's own calibration check. Anything materially above
    # the nominal 0.5% means that verifier's threshold does not transfer across
    # prompt ranges -- a property of the verifier, not of speculation, and it has
    # to be said out loud or the speculative rows below cannot be read.
    tol = 4.0 * cfg.max_fpr
    bad = [(d, tpr["honest_null"][d][0]) for d in VERIFIERS
           if tpr["honest_null"][d][0] > tol]
    print(f"\n  Calibration check: `honest_null` should sit at the nominal "
          f"{cfg.max_fpr:.1%} on every column.")
    if not bad:
        print(f"  It does (max {max(tpr['honest_null'][d][0] for d in VERIFIERS):.2%}, "
              f"tolerance {tol:.1%}). The threshold is not the problem.")
    else:
        print("  It does NOT, on: "
              + ", ".join(f"{d} ({v:.1%})" for d, v in bad)
              + f" (tolerance {tol:.1%}).")
        print("  Those columns are miscalibrated ACROSS PROMPT RANGES: the same honest\n"
              "  server on different prompts already exceeds the FPR budget, so their\n"
              "  speculative rows measure prompt difficulty as much as speculation and\n"
              "  cannot be read as false-positive rates. The columns within tolerance ("
              + ", ".join(d for d in VERIFIERS if tpr["honest_null"][d][0] <= tol)
              + ")\n  can.")

    # ------------------------------------------------- 5. honesty certificate
    print("\n" + "=" * 78)
    print("5. Honesty certificate: the emitted tokens, judged WITHOUT the seed")
    print("=" * 78)
    print(f"{'arm':>19} | {'mean NLL under M':>18} {'mean rank in M':>16} "
          f"{'seed replay agrees':>19} {'mean margin':>13}")
    print("-" * 88)
    cert = {}
    for name in ["honest"] + [a for a, _ in ARMS]:
        ts = honest if name == "honest" else scored[name]
        ce, rk, dm = ts.scores["cross_entropy"], ts.scores["token_toploc"], ts.scores["token_difr"]
        # A token_difr margin of exactly 0 means the verifier's replay under the
        # shared seed reproduced the claimed token. That share is the whole
        # mechanism, stated without a threshold, a batch or a metric.
        cert[name] = {"nll": float(ce.mean()), "nll_se": float(ce.std() / np.sqrt(len(ce))),
                      "rank": float(rk.mean()), "rank_se": float(rk.std() / np.sqrt(len(rk))),
                      "agree": float(np.mean(dm == 0.0)), "margin": float(dm.mean()),
                      "n": int(len(ce))}
        c = cert[name]
        print(f"{name:>19} | {c['nll']:>11.4f}+-{c['nll_se']:.4f} "
              f"{c['rank']:>9.3f}+-{c['rank_se']:.3f} {c['agree']:>18.1%} "
              f"{c['margin']:>13.4f}")
    print("\n  Columns 1-2 read the claimed tokens against the recomputed reference and\n"
          "  need NO seed. Columns 3-4 are the seeded replay. An honest speculative\n"
          "  server matches the honest server on 1-2 and not on 3-4 -- which is the\n"
          "  finding: what the seeded verifier reports is a break in SEED\n"
          "  SYNCHRONISATION, not in the distribution the tokens were drawn from.")
    print(f"\n  The mechanism in one number: the verifier's replay reproduces "
          f"{cert['honest']['agree']:.1%} of an\n  honest sequential server's tokens and only "
          f"{cert['honest_spec']['agree']:.1%} of an honest speculative server's --\n"
          f"  against {cert['seed_43']['agree']:.1%} for the wrong-seed ATTACK.")

    # -------------------------------------------------------- 6. the alibi cost
    print("\n" + "=" * 78)
    print("6. What tolerating speculative decoding costs")
    print("=" * 78)
    print(f"{'attack':>19} | {'best AUC (all 4)':>18} {'best, no token_difr':>21} "
          f"{'cost':>8}")
    print("-" * 78)
    alibi = {}
    for name, _ in ARMS:
        if name in HONEST_ARMS:
            continue
        full = max((auc[name][d][0], d) for d in VERIFIERS)
        free = max((auc[name][d][0], d) for d in SEED_FREE)
        alibi[name] = {"full": full[0], "full_by": full[1],
                       "seed_free": free[0], "seed_free_by": free[1],
                       "cost": full[0] - free[0]}
        print(f"{name:>19} | {full[0]:>10.3f} ({full[1][:6]:>6}) "
              f"{free[0]:>12.3f} ({free[1][:6]:>6}) {full[0]-free[0]:>8.3f}")
    print("\n  A provider that speculates cannot be checked with `token_difr` -- the\n"
          "  detector flags it at the rate in table 4 while it is doing nothing wrong.\n"
          "  So the row above without `token_difr` is the portfolio a verifier actually\n"
          "  has against a provider that is ALLOWED to speculate.")

    art = {
        "model": MODEL, "draft": DRAFT, "gamma": GAMMA,
        "n_prompts": N_PROMPTS, "n_tokens": N_TOKENS, "n_seeds": N_SEEDS,
        "batch": batch, "eval_pool": eval_split, "pool_ratio": batch / eval_split,
        "verifiers": VERIFIERS, "seed_free": SEED_FREE,
        "spec_runs": spec_runs,
        "auc": {a: {d: list(v) for d, v in m.items()} for a, m in auc.items()},
        "tpr": {a: {d: list(v) for d, v in m.items()} for a, m in tpr.items()},
        "d_prime": dprime, "certificate": cert, "alibi": alibi,
        "seconds": time.time() - t0,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(art, indent=2, sort_keys=True))
    print(f"\nwrote {OUT}")
    print(f"total {time.time()-t0:.1f}s")


if __name__ == "__main__":
    main()
